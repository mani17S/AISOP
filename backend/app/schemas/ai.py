"""
AISOP AI/LLM Schemas & Data Contracts.

In accordance with ADR-001 (Direct Lightweight LLM Abstraction):
Defines standardized, immutable Pydantic contracts for message representations,
inference requests, structured responses, token usage metrics, and provider health.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class MessageRole(StrEnum):
    """Supported roles in a chat conversation."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"


class LLMMessage(BaseModel):
    """Individual message within a conversation."""

    model_config = ConfigDict(frozen=True)

    role: MessageRole = Field(
        description="The role of the message participant (system, user, assistant)."
    )
    content: str = Field(
        min_length=1,
        description="Text content of the message.",
    )


class LLMRequest(BaseModel):
    """Standardized request payload for LLM inference."""

    model_config = ConfigDict(frozen=True)

    messages: list[LLMMessage] = Field(
        min_length=1,
        description="Chronological list of conversation messages.",
    )
    model: str | None = Field(
        default=None,
        description="Optional model override. Defaults to provider configured model if None.",
    )
    temperature: float | None = Field(
        default=None,
        ge=0.0,
        le=2.0,
        description="Sampling temperature. Low values (0.0-0.3) provide deterministic SOC analysis.",
    )
    max_tokens: int | None = Field(
        default=None,
        gt=0,
        description="Maximum tokens to generate. None uses the provider default.",
    )
    json_mode: bool = Field(
        default=False,
        description="If True, instructs the provider to enforce valid JSON formatting.",
    )
    think: bool | None = Field(
        default=False,
        description="If False, disables thinking/reasoning tokens for models that support it (e.g. qwen3:4b) to preserve token budget for structured JSON output.",
    )


class TokenUsage(BaseModel):
    """Token consumption and inference latency metrics."""

    model_config = ConfigDict(frozen=True)

    prompt_tokens: int = Field(
        default=0,
        ge=0,
        description="Number of tokens in the prompt context.",
    )
    completion_tokens: int = Field(
        default=0,
        ge=0,
        description="Number of tokens generated by the model.",
    )
    total_tokens: int = Field(
        default=0,
        ge=0,
        description="Aggregate token count (prompt + completion).",
    )
    duration_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Execution duration in milliseconds.",
    )


class LLMResponse(BaseModel):
    """Standardized response from an LLM provider."""

    model_config = ConfigDict(frozen=True)

    content: str = Field(
        description="Generated text content from the assistant.",
    )
    role: MessageRole = Field(
        default=MessageRole.ASSISTANT,
        description="Role of the responder (always assistant).",
    )
    model: str = Field(
        description="Identifier of the model that produced the response.",
    )
    usage: TokenUsage = Field(
        default_factory=TokenUsage,
        description="Token accounting and execution latency metrics.",
    )
    finish_reason: str = Field(
        default="stop",
        description="Reason generation terminated (e.g. 'stop', 'length').",
    )
    raw_response: dict[str, Any] | None = Field(
        default=None,
        description="Optional raw dictionary response from the underlying provider for diagnostics.",
    )


class ProviderHealthResponse(BaseModel):
    """Health and diagnostic status of an LLM provider."""

    model_config = ConfigDict(frozen=True)

    status: Literal["healthy", "degraded", "unavailable"] = Field(
        description="Provider operational health state.",
    )
    model: str = Field(
        description="Target model configured for the provider.",
    )
    provider: str = Field(
        default="ollama",
        description="Provider identifier (e.g. 'ollama').",
    )
    latency_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Health probe round-trip latency in milliseconds.",
    )
    error: str | None = Field(
        default=None,
        description="Diagnostic error message if provider is degraded or unavailable.",
    )
